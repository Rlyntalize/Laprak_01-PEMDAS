putaran = 5
jarak = 14
keliling = jarak / putaran
pi = 3.14

jari_jari = keliling / (2 * pi)

print("Diketahui :")
print("Pak Dengklek mengelilingi taman =", putaran, "Putaran")
print("Jarak tempuh Pak Dengklek =", jarak, "Kilometer")

print("\nJawaban :")
print("Jari-jari taman yang dikelilingi Pak Dengklek adalah", format(jari_jari, ".2f"), "Kilometer")